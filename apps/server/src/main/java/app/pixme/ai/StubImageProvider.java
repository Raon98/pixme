package app.pixme.ai;

import java.awt.image.BufferedImage;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.util.List;
import java.util.Random;

import javax.imageio.ImageIO;

import app.pixme.common.ApiException;
import app.pixme.common.ErrorCode;
import org.springframework.stereotype.Component;

/**
 * Local development provider.
 *
 * <p>Draws a real (if crude) pixel character procedurally so the entire create
 * flow — upload, analysis, generation, publish, square placement — is
 * exercisable offline, in tests and in CI without provider credentials or
 * spend. Selected with {@code pixme.ai.provider=stub}.
 *
 * <p>It honours the framing rule: a selfie analysis produces a bust, a
 * full-body analysis produces legs and shoes. That matters because framing is
 * exactly the behaviour most likely to regress.
 */
@Component
public class StubImageProvider implements PixelImageProvider {

    private static final int CANVAS = 256;
    private static final int PIXEL = 8;

    private static final int[] SKIN = {0xF2, 0xC9, 0xA8};
    private static final int[] OUTLINE = {0x2E, 0x2B, 0x26};

    @Override
    public String name() {
        return "stub";
    }

    @Override
    public SafetyVerdict checkSafety(byte[] image, String mimeType) {
        return SafetyVerdict.ok();
    }

    @Override
    public ImageAnalysis analyzeImage(byte[] image, String mimeType) {
        // Deterministic per image so repeated local runs are reproducible.
        Random random = new Random(image.length);
        ImageAnalysis.Framing framing = ImageAnalysis.Framing.values()[random.nextInt(3)];

        List<ImageAnalysis.Garment> garments = framing == ImageAnalysis.Framing.FULL_BODY
                ? List.of(
                        new ImageAnalysis.Garment("TOP", "t-shirt", "white", "solid", 0, "regular"),
                        new ImageAnalysis.Garment("OUTER", "denim jacket", "indigo", "solid", 1, "oversized"),
                        new ImageAnalysis.Garment("BOTTOM", "straight jeans", "blue", "solid", 0, "regular"))
                : List.of(
                        new ImageAnalysis.Garment("TOP", "hoodie", "charcoal", "solid", 0, "oversized"));

        return new ImageAnalysis(
                framing,
                true,
                new ImageAnalysis.Hair("medium", "straight", "dark brown", "bangs"),
                new ImageAnalysis.Face("calm", random.nextBoolean(), "round", false, null),
                garments,
                List.of(new ImageAnalysis.Accessory("BAG", "black", "crossbody")),
                framing == ImageAnalysis.Framing.FULL_BODY
                        ? new ImageAnalysis.Footwear("sneakers", "white")
                        : null,
                "quiet weekday",
                List.of("#2E2B26", "#4A6FA5", "#F5F0E6"),
                "generated by the local stub provider");
    }

    @Override
    public GeneratedCharacter generateCharacter(GenerationRequest request) {
        ImageAnalysis analysis = request.analysis() != null
                ? request.analysis()
                : analyzeImage(request.sourceImage(), request.sourceMimeType());
        return render(request, analysis);
    }

    @Override
    public GeneratedCharacter generateVariant(GenerationRequest request) {
        return generateCharacter(request);
    }

    private GeneratedCharacter render(GenerationRequest request, ImageAnalysis analysis) {
        BufferedImage canvas = new BufferedImage(CANVAS, CANVAS, BufferedImage.TYPE_INT_ARGB);
        Random random = new Random(request.seed());

        int[] top = colorFor(analysis, "TOP", random);
        int[] outer = colorFor(analysis, "OUTER", random);
        int[] bottom = colorFor(analysis, "BOTTOM", random);
        int[] hair = {0x3A, 0x2A, 0x22};

        // 32x32 logical grid at 8px per pixel.
        // head
        fill(canvas, 11, 5, 10, 8, hair);
        fill(canvas, 12, 8, 8, 6, SKIN);
        fill(canvas, 14, 10, 1, 1, OUTLINE);
        fill(canvas, 17, 10, 1, 1, OUTLINE);
        fill(canvas, 15, 12, 2, 1, OUTLINE);

        if (analysis.face() != null && analysis.face().glasses()) {
            fill(canvas, 13, 10, 6, 1, OUTLINE);
        }

        // torso + outer layer
        fill(canvas, 11, 14, 10, 8, top);
        if (outer != null) {
            fill(canvas, 10, 14, 2, 8, outer);
            fill(canvas, 20, 14, 2, 8, outer);
        }
        // arms
        fill(canvas, 8, 15, 2, 6, outer != null ? outer : top);
        fill(canvas, 22, 15, 2, 6, outer != null ? outer : top);

        // Framing rule: only draw a lower body when the photo showed one.
        if (analysis.showsLowerBody() && bottom != null) {
            fill(canvas, 12, 22, 3, 6, bottom);
            fill(canvas, 17, 22, 3, 6, bottom);
            if (analysis.showsFootwear()) {
                int[] shoes = {0xF0, 0xF0, 0xF0};
                fill(canvas, 11, 28, 4, 2, shoes);
                fill(canvas, 17, 28, 4, 2, shoes);
            }
        }

        try {
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            ImageIO.write(canvas, "png", out);
            return new GeneratedCharacter(
                    out.toByteArray(),
                    "image/png",
                    name(),
                    "stub-v1",
                    request.promptVersion(),
                    analysis);
        } catch (IOException exception) {
            throw new ApiException(ErrorCode.INTERNAL_ERROR, "스텁 이미지를 만들지 못했어요.");
        }
    }

    private int[] colorFor(ImageAnalysis analysis, String slot, Random random) {
        boolean present = analysis.garments() != null
                && analysis.garments().stream()
                        .anyMatch(garment -> slot.equals(garment.slot()));
        if (!present) {
            return slot.equals("OUTER") || slot.equals("BOTTOM") ? null : fallback(random);
        }
        return fallback(random);
    }

    private int[] fallback(Random random) {
        return new int[] {
            100 + random.nextInt(120), 100 + random.nextInt(120), 100 + random.nextInt(120)
        };
    }

    /** Fills a logical pixel rectangle, scaled up by {@link #PIXEL}. */
    private void fill(BufferedImage canvas, int x, int y, int width, int height, int[] rgb) {
        if (rgb == null) {
            return;
        }
        int argb = 0xFF000000 | (rgb[0] << 16) | (rgb[1] << 8) | rgb[2];
        for (int px = x * PIXEL; px < (x + width) * PIXEL && px < CANVAS; px++) {
            for (int py = y * PIXEL; py < (y + height) * PIXEL && py < CANVAS; py++) {
                canvas.setRGB(px, py, argb);
            }
        }
    }
}
